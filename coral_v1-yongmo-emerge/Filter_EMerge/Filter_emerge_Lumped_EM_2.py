#!/usr/bin/env python3
"""
============================================================
13차 체비셰프 저역통과필터 (LPF) EMerge 시뮬레이션 파일
============================================================
- Lumped Element 기반 필터 설계
- 50 Ohm 임피던스 매칭
- UMFPACK 솔버 사용
============================================================
"""

import emerge as em      # EMerge 전자기 시뮬레이션 라이브러리
import gmsh              # GMSH 메쉬 생성 라이브러리
import numpy as np       # 수치 연산 라이브러리
from pathlib import Path # 파일 경로 처리 라이브러리

def main():
    # ========================================================
    # 1. 출력 디렉토리 설정
    # ========================================================
    OUTPUT_DIR = Path("/scratch/home/yongmo0415/Lumped_2")  # 슈퍼컴퓨터 결과 저장 경로
    
    # ========================================================
    # 2. 단위 정의
    # ========================================================
    mm = 0.001  # 밀리미터를 미터로 변환하는 스케일 팩터
    
    # ========================================================
    # 3. PCB 기판 및 재료 파라미터
    # ========================================================
    th = 0.4           # PCB 기판 두께 [mm]
    er = 4.0           # 기판 유전율 (FR-4 유사)
    tand = 0.013       # 손실 탄젠트 (유전 손실)
    cond_t = 0.017     # 도체 (트레이스/그라운드) 두께 [mm]
    cond_s = 4.1e7     # 도체 전도도 [S/m] (금 기준)
    
    # ========================================================
    # 4. 필터 트레이스 치수 파라미터
    # ========================================================
    PORT_W = 0.8012    # 입출력 포트 폭 [mm] (50 Ohm 임피던스용)
    PORT_L = 2.0       # 입출력 포트 피드라인 길이 [mm]
    L_W, C_W = 0.238, 2.914  # 인덕터(L) 폭, 커패시터(C) 폭 [mm]
    
    # ========================================================
    # 5. 13차 체비셰프 필터 소자 길이 [mm]
    # ========================================================
    # 인덕터 길이 (L1 ~ L13, 홀수번 소자)
    L1, L3, L5, L7, L9, L11, L13 = 1.203, 2.121, 2.229, 2.248, 2.229, 2.121, 1.203
    # 커패시터 길이 (C2 ~ C12, 짝수번 소자)
    C2, C4, C6, C8, C10, C12 = 1.434, 1.511, 1.527, 1.527, 1.511, 1.434
    
    # ========================================================
    # 6. 기하 배치 파라미터
    # ========================================================
    CENTER_Y = 5.0 + 5.0  # 필터 트레이스 Y축 중심 위치 [mm]
    
    # ========================================================
    # 7. 메쉬 크기 계산 (주파수 기반)
    # ========================================================
    MAX_FREQ = 50e9  # 최대 시뮬레이션 주파수 [Hz] = 50 GHz
    c = 3e8          # 빛의 속도 [m/s]
    lambda_val = (c / MAX_FREQ) * 1000  # 최소 파장 [mm]
    
    # 메쉬 에지 크기 설정 (파장 기반)
    MAX_EDGE = lambda_val / 3    # 최대 에지 크기: λ/3 [mm]
    MIN_EDGE = lambda_val / 30   # 최소 에지 크기: λ/30 [mm]
    PCB_EDGE_SIZE = lambda_val / 10  # PCB 에지 메쉬 크기: λ/10 [mm]
    
    # ========================================================
    # 8. 에어박스 높이 설정
    # ========================================================
    Hair = 18.75  # 에어박스 높이 (기판 위쪽 공간) [mm]
    
    # ========================================================
    # 9. 재료 정의
    # ========================================================
    pcbmat = em.Material(er=er, tand=tand)           # PCB 기판 재료 (유전체)
    condmat = em.Material(cond=cond_s, name="Gold")  # 도체 재료 (금)
    airmat = em.Material(name="Air")                 # 공기 재료
    
    # ========================================================
    # 10. 시뮬레이션 객체 생성
    # ========================================================
    m = em.Simulation('chebyshev_lpf_lumped_2')  # 시뮬레이션 이름 설정
    m.check_version("2.0.0")                     # EMerge 버전 확인
    
    # ========================================================
    # 11. 솔버 설정
    # ========================================================
    m.set_solver(em.EMSolver.UMFPACK)  # UMFPACK 직접 솔버 사용 (대규모 행렬용)
    
    # ========================================================
    # 12. PCB 레이아웃 객체 생성
    # ========================================================
    layouter = em.geo.PCB(
        th,                           # 기판 두께
        unit=mm,                      # 단위 스케일 (mm → m)
        material=pcbmat,              # 기판 재료
        trace_material=condmat,       # 트레이스 재료
        trace_thickness=cond_t * mm,  # 트레이스 두께 [m]
        thick_traces=True,            # 3D 두께 트레이스 활성화
        layers=2                      # 2층 PCB (상층 트레이스 + 하층 그라운드)
    )
    
    # ========================================================
    # 13. 필터 전체 치수 계산
    # ========================================================
    # 필터 전체 폭 = 포트피드 + 모든 L/C 소자 길이 합
    TOTAL_WIDTH = PORT_L + L1 + C2 + L3 + C4 + L5 + C6 + L7 + C8 + L9 + C10 + L11 + C12 + L13 + PORT_L
    TOTAL_HEIGHT = 10.0  # 필터 전체 높이 [mm]
    
    # ========================================================
    # 14. 마진 및 오프셋 계산
    # ========================================================
    X_MARGIN = TOTAL_WIDTH / 2   # X축 마진 (에어박스용)
    Y_MARGIN = TOTAL_HEIGHT / 2  # Y축 마진 (에어박스용)
    
    x_margin = 1.0  # PCB 좌우 마진 [mm]
    X_OFFSET = (TOTAL_WIDTH + 2 * x_margin) / 2  # X축 중심 오프셋
    
    # ========================================================
    # 15. 필터 트레이스 경로 생성 (체인 패턴)
    # ========================================================
    # new(): 시작점 설정 (x, y, 폭, 방향)
    # store(): 현재 위치를 포트용으로 저장
    # straight(): 직선 트레이스 생성 (길이, 폭)
    layouter.new(X_OFFSET + x_margin, CENTER_Y, PORT_W, (1,0)).store('p1')\
        .straight(PORT_L, PORT_W)\
        .straight(L1, L_W).straight(C2, C_W)\
        .straight(L3, L_W).straight(C4, C_W)\
        .straight(L5, L_W).straight(C6, C_W)\
        .straight(L7, L_W)\
        .straight(C8, C_W).straight(L9, L_W)\
        .straight(C10, C_W).straight(L11, L_W)\
        .straight(C12, C_W).straight(L13, L_W)\
        .straight(PORT_L, PORT_W).store('p2')
    
    # ========================================================
    # 16. 경로를 폴리곤으로 컴파일
    # ========================================================
    polies = layouter.compile_paths(merge=True)  # merge=True: 인접 폴리곤 병합
    
    # ========================================================
    # 17. PCB 경계 마진 설정
    # ========================================================
    y_common_margin = (TOTAL_HEIGHT - C_W) / 2  # Y축 공통 마진 계산
    y_margin_top = y_common_margin     # 상단 마진
    y_margin_bottom = y_common_margin  # 하단 마진
    
    # PCB 경계 결정 (트레이스 주변 마진 적용)
    layouter.determine_bounds(leftmargin=x_margin, topmargin=y_margin_top, rightmargin=x_margin, bottommargin=y_margin_bottom)
    
    # ========================================================
    # 18. PCB 지오메트리 생성
    # ========================================================
    pcb = layouter.generate_pcb(True, merge=True)  # True: 기판 생성, merge: 병합
    
    # ========================================================
    # 19. PCB 및 에어박스 치수 계산 [m]
    # ========================================================
    PCB_X = (TOTAL_WIDTH + 2 * x_margin) * mm  # PCB X 크기 [m]
    PCB_Y = TOTAL_HEIGHT * mm                   # PCB Y 크기 [m]
    AIRBOX_X = PCB_X * 2                        # 에어박스 X 크기 (PCB의 2배)
    AIRBOX_Y = TOTAL_HEIGHT * mm + 2 * Y_MARGIN * mm  # 에어박스 Y 크기
    
    # ========================================================
    # 20. 그라운드 플레인 생성
    # ========================================================
    ground = em.geo.Box(
        PCB_X,                                    # X 크기 [m]
        PCB_Y,                                    # Y 크기 [m]
        cond_t * mm,                              # Z 크기 (두께) [m]
        position=(X_OFFSET * mm, Y_MARGIN * mm, -(th + cond_t) * mm)  # 위치 (PCB 하단)
    )
    ground.set_material(condmat)  # 도체 재료 적용
    
    # ========================================================
    # 21. 에어박스 생성 (시뮬레이션 영역)
    # ========================================================
    AIRBOX_Z_START = -(th + cond_t)        # 에어박스 Z 시작점 (그라운드 하단)
    AIRBOX_HEIGHT = (th + cond_t) + Hair   # 에어박스 총 높이
    
    airbox = em.geo.Box(
        AIRBOX_X,                           # X 크기 [m]
        AIRBOX_Y,                           # Y 크기 [m]
        AIRBOX_HEIGHT * mm,                 # Z 크기 [m]
        position=(0, 0, AIRBOX_Z_START * mm)  # 위치
    )
    airbox.material = airmat  # 공기 재료 적용
    
    # ========================================================
    # 22. 럼프드 포트 생성
    # ========================================================
    p1 = layouter.lumped_port(layouter.load('p1'))  # 포트 1 (입력)
    p2 = layouter.lumped_port(layouter.load('p2'))  # 포트 2 (출력)
    
    # ========================================================
    # 23. 지오메트리 커밋
    # ========================================================
    m.commit_geometry()  # 모든 지오메트리를 시뮬레이션에 적용
    
    # ========================================================
    # 24. 주파수 스윕 설정
    # ========================================================
    # 1 MHz ~ 50 GHz 범위 (저주파 3개 + 1 GHz 간격 고주파)
    freq_list = [1e6, 10e6, 100e6] + list(np.arange(1e9, 50e9 + 1e9, 1e9))
    m.mw.set_frequency(freq_list)  # 주파수 리스트 설정
    
    # ========================================================
    # 25. 메쉬 설정
    # ========================================================
    # 트레이스 상면에 정밀 메쉬 적용
    m.mesher.set_boundary_size(polies.face('+z'), MIN_EDGE * mm, growth_rate=10)
    # PCB에 중간 밀도 메쉬 적용
    m.mesher.set_boundary_size(pcb, PCB_EDGE_SIZE * mm)
    
    # GMSH 전역 메쉬 크기 설정
    gmsh.option.setNumber("Mesh.MeshSizeMin", MIN_EDGE * mm)  # 최소 메쉬 크기
    gmsh.option.setNumber("Mesh.MeshSizeMax", MAX_EDGE * mm)  # 최대 메쉬 크기
    
    # ========================================================
    # 26. 메쉬 생성
    # ========================================================
    m.generate_mesh()  #메쉬 생성
    
    # ========================================================
    # 27. 경계 조건 설정
    # ========================================================
    # 럼프드 포트 경계조건 (50 Ohm 임피던스)
    port1 = m.mw.bc.LumpedPort(p1, 1, Z0=50)  # 포트 1: 입력 포트
    port2 = m.mw.bc.LumpedPort(p2, 2, Z0=50)  # 포트 2: 출력 포트
    
    # 흡수 경계조건 (ABC) - 에어박스 5개 면에 적용
    # order=2: 2차 ABC, abctype='B': Bayliss-Turkel 타입
    m.mw.bc.AbsorbingBoundary(airbox.top, order=2, abctype='B')    # 상단
    m.mw.bc.AbsorbingBoundary(airbox.left, order=2, abctype='B')   # 좌측
    m.mw.bc.AbsorbingBoundary(airbox.right, order=2, abctype='B')  # 우측
    m.mw.bc.AbsorbingBoundary(airbox.front, order=2, abctype='B')  # 전면
    m.mw.bc.AbsorbingBoundary(airbox.back, order=2, abctype='B')   # 후면
    
    # ========================================================
    # 28. 주파수 스윕 시뮬레이션 실행
    # ========================================================
    data = m.mw.run_sweep(
        parallel=True,        # 병렬 처리 활성화
        n_workers=32,         # 병렬 워커 수 (CPU 코어)
        frequency_groups=53,  # 주파수 그룹 수 (각 그룹별 메모리 관리)
        multi_processing=True # 멀티프로세싱 활성화
    )
    
    # ========================================================
    # 29. S-파라미터 추출
    # ========================================================
    grid = data.scalar.grid      # 결과 그리드 데이터
    f = grid.freq                # 주파수 배열
    S11 = grid.S(1, 1)           # S11: 반사 계수 (입력 반사)
    S21 = grid.S(2, 1)           # S21: 전송 계수 (삽입 손실)
    
    # S-파라미터를 dB로 변환
    S11_dB = 20 * np.log10(np.abs(S11) + 1e-12)  # +1e-12: log(0) 방지
    S21_dB = 20 * np.log10(np.abs(S21) + 1e-12)
    
    # ========================================================
    # 30. 결과 저장
    # ========================================================
    OUTPUT_DIR.mkdir(exist_ok=True, parents=True)  # 출력 디렉토리 생성
    s2p_file = OUTPUT_DIR / "5_25_lumped_2_18.75.s2p"  # S2P 파일 경로
    
    # Touchstone S2P 형식으로 내보내기
    grid.export_touchstone(str(s2p_file), Z0ref=50, format="RI", funit="GHZ")
    print(f"✅ S2P 저장 완료: {s2p_file}")
    
    # ========================================================
    # 31. 시뮬레이션 저장
    # ========================================================
    m.save()  # 시뮬레이션 상태 저장

# ========================================================
# 메인 실행부
# ========================================================
if __name__ == "__main__":
    main()
